package com.ruleup.ruleup_backend.score.domain;

/**
 * 점수가 움직인 <b>사건</b> — 내 티어 상세 조회 API 의 {@code recentChanges[].reason}.
 *
 * <p>회계 분류(transaction_type)와 층이 다르다. 강퇴 −15 와 부정행위 −50 은 회계적으로 둘 다
 * 차감이지만 사용자에게는 전혀 다른 사건이라 화면이 구분해 보여줘야 한다.
 *
 * <p>고정 감점은 사건성 3종뿐이다 — 부정행위 −50, 권한 미허용 강퇴 −15, 중도 탈퇴 최대 −15.
 * 사이클 성공·실패의 점수는 티어별 주간 배점을 정수 산식으로 나눈 값이라 고정 수치가 아니다
 * (마이페이지 오픈 이슈 #1 해소).
 *
 * <p>구 {@code KICK_REPORT}(신고 강퇴 −30)는 신고→강퇴 경로가 폐지되며 함께 사라졌다.
 * 신고 검토로 계정 제재를 받으면 전 챌린지에서 자동 탈퇴되지만 <b>감점은 없다</b>.
 */
public enum ScoreReason {

    /** 사이클 성공 정산. */
    CYCLE_SUCCESS,

    /** 사이클 실패 정산. */
    CYCLE_FAIL,

    /** 중도 탈퇴 — 최대 −15. 해당 챌린지를 1년 이상 성공해 왔다면 면제된다. */
    LEAVE,

    /** 연속 실패 강퇴 — 감점 없음(0). 사건 자체는 이력에 남는다. */
    KICK_FAIL,

    /** 권한 미허용 강퇴 — −15. */
    KICK_PERMISSION,

    /** 부정행위 검출 — −50. 검출 1회로 해당 챌린지 강퇴·영구 차단이 함께 확정되며 강퇴 감점을 중복 부과하지 않는다. */
    CHEAT,

    /** 이의 인용 소급 — 정상 성공과 동일하게 복원한다. */
    APPEAL_RESTORE
}

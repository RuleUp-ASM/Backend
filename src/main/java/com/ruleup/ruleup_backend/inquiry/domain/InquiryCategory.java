package com.ruleup.ruleup_backend.inquiry.domain;

/**
 * CS 접수 분류 <b>6종</b> — 앱 운영 정책 § 5.1.
 *
 * <p>구 5종(계정/인증/결제/신고/기타)에서 개편된 값이다. <b>결제는 두지 않는다</b> —
 * 1차 출시에 미탑재라 접수될 수 없는 분류이고, 없는 분류를 남겨 두면 유저가 그걸 고른 뒤
 * 운영자가 다시 옮겨야 한다. 결제 도입(Phase 2) 때 {@code PAYMENT} 를 추가한다.
 *
 * <p>분류마다 <b>1차 확인 항목</b>이 다르다는 점이 이 목록의 존재 이유다. 운영자는 이 값을 보고
 * 어떤 로그부터 볼지 정한다 — 그래서 유저가 잘못 고른 분류는 운영자가 바꿀 수 있고,
 * <b>바꾼 사실은 유저에게 노출하지 않는다</b>(고른 게 틀렸다고 알릴 이유가 없다).
 */
public enum InquiryCategory {

    /** 인증·판정 — 자동 인증 미수집, 판정 결과 이상, 판정·확정 시각. 1차 확인: 판정 로그. */
    VERIFICATION,

    /** 권한·기기 연동 — 위치·백그라운드 위치, Health Connect, UsageStats, Play Integrity. */
    DEVICE_PERMISSION,

    /** 챌린지·그룹 — 생성·참여·정원·방 스레드·공지. */
    CHALLENGE_GROUP,

    /** 계정·로그인 — 소셜 로그인, 닉네임, 탈퇴·복구. */
    ACCOUNT_LOGIN,

    /**
     * 신고·제재 — 신고 처리 결과 문의와 <b>운영자 제재 재검토</b>가 이 분류로 들어온다(§ 5.6).
     * 재검토의 대상·횟수·회신 기한은 운영자 제재 정책 § 7 이 원본이고 여기는 접수 경로일 뿐이다.
     */
    REPORT_SANCTION,

    /** 오류·제안·기타 — 크래시·버그, 기능 제안, 그 밖의 문의. 1차 확인: 오류 로그 ID 대조. */
    ERROR_ETC
}

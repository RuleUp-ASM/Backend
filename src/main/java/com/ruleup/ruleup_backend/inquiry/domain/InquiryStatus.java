package com.ruleup.ruleup_backend.inquiry.domain;

/**
 * 문의 상태 — 앱 운영 정책 § 5.4. <b>둘뿐이고 그 사이 전이가 없다.</b>
 *
 * <p>「검토중」 같은 중간 상태를 두지 않는 이유는 신고 검토와 같다 — 운영자가 2명이라 동시성
 * 제어보다 이력 추적이 중요하고, 중간 상태는 전이 API 를 하나 더 만들면서 정작 유저에게는
 * 아무 정보도 주지 않는다. <b>답변 등록이 곧 종결</b>이다.
 */
public enum InquiryStatus {

    /** 접수 직후. 운영자 답변을 기다린다. */
    RECEIVED,

    /**
     * 답변 완료 = 종결. <b>재문의 경로가 없다</b>(§ 5.5) — 같은 사안이라도 다시 물으려면
     * 새 문의로 접수하고, 새 문의에도 같은 SLA 가 적용된다.
     */
    ANSWERED
}

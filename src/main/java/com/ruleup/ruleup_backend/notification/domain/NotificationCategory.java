package com.ruleup.ruleup_backend.notification.domain;

/**
 * 알림 분류 — <b>런타임 분기의 유일한 근거</b>다. 알림 및 알림함 공통 5-1.
 *
 * <p>야간에 보류할지, 설정 토글을 볼지, 중복을 막을지가 전부 여기서 갈린다. 분류는 알림 타입에
 * 고정된 값이며 발송 시점에 계산하지 않는다.
 *
 * <p>DB 에도 <b>코드 상수로 고정</b>하고 테이블로 두지 않는다 — 분류가 바뀌면 법적 의미가
 * 바뀌므로 배포 없이 바꿀 수 있게 하면 안 된다.
 */
public enum NotificationCategory {

    /**
     * 필수 — 제재·고지 의무 성격. 끌 수 없고 설정 화면에 <b>토글 컴포넌트 자체를 렌더링하지 않는다</b>.
     * <b>시각 무관 즉시 발송</b>이며 야간 보류의 유일한 예외다. 중복 제어도 적용하지 않는다.
     */
    A,

    /** 기능 — 서비스 이용 알림. 유형별 토글 + 챌린지별 음소거, 야간 보류 후 08:00 발송, 24시간 중복 제어. */
    B,

    /** 마케팅·이벤트 — 토글이 수신 동의 상태와 연동된다. <b>08~21시에만 발송</b>(정보통신망법). */
    C;

    /** DB 저장값 — CHAR(1). */
    public String code() {
        return name();
    }
}

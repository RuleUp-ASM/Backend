package com.ruleup.ruleup_backend.push;

import java.util.List;

/**
 * 안드로이드 알림 채널 — <b>단일 채널 {@code ruleup_default} 로 확정</b>(2026-09-07).
 *
 * <p>유형별로 쪼개면(계정·챌린지·마케팅·리마인더 4채널) 서버가 모르는 <b>두 번째 게이트</b>가
 * 생긴다. 지금 정책은 "OS 권한 상태는 서버가 알 수 없으니 발송 판정에 쓰지 않는다"인데, 채널을
 * 나누면 그 문제가 채널 수만큼 늘어난다. {@code notification_deliveries} 에 SUCCESS 로 찍혔는데
 * 사용자는 받지 못한 상태가 정상적으로 존재하게 되고, CS 는 서버 로그로 그걸 구분할 수 없다.
 *
 * <p>제어 수단이 없어서 하나로 두는 것이 아니다. 앱 안에 마스터 · 그룹 3종 · 챌린지별 음소거의
 * 3계층 토글이 이미 있고 "끌 수 없는 푸시는 없다"가 정책이다. 채널을 나눠서 얻는 것은 <b>OS
 * 설정에서의 접근성</b>이지 제어 자체가 아니다.
 *
 * <h2>분할 가능성은 열어 둔다</h2>
 *
 * <p>지금 쪼개지 않는 것은 <b>시점</b> 때문이다. 채널 ID 는 출시 후 바꿀 수 없는데 그룹 체계가
 * 아직 굳지 않았고(감시자를 별도 토글 그룹으로 뺄지, 마케팅 동의 철회 고지 타입을 추가할지가
 * 열려 있다), 그룹이 늘면 채널을 추가해야 하는데 기존 채널은 기기에 계속 남는다.
 *
 * <p>되돌리기 비용도 비대칭이다. <b>단일 → 분할은 가능</b>하지만(새 채널을 만들고 이 채널을 쓰지
 * 않으면 된다. 다만 새 채널이 전부 기본 활성으로 생성돼 이 채널을 꺼 뒀던 사용자에게 알림이 다시
 * 간다), <b>분할 → 통합은 훨씬 나쁘다</b> — 채널별로 흩어진 사용자 설정이 통째로 무시되고 어떤
 * 채널을 껐든 하나로 다시 전부 오게 된다. 불확실하면 단일로 시작하는 쪽이 싸다.
 *
 * <p><b>전환 조건</b> — 릴리즈 후 4주 관측 항목의 「앱 알림 차단율」이 실제로 오르면 그때 쪼갠다.
 * 그 시점에는 그룹 체계도 굳어 있고, 어느 유형이 차단을 유발하는지 데이터로 알 수 있어 채널을 몇
 * 개로 나눌지도 근거를 갖고 정할 수 있다. 쪼갠다면 <b>{@code ruleup_default} + 마케팅 2채널</b>이
 * 먼저다 — 마케팅은 이미 동의 기반이라 별도 취급이 자연스럽고, 정합성이 깨져도 서비스 고지가
 * 아니라 CS 부담이 작으며, {@code priority=high} 고정이 마케팅 캠페인까지 강퇴 고지와 같은 강도로
 * 울리게 하는 현재 계약의 부작용을 그것만으로 막을 수 있다.
 *
 * <p>4채널(그룹 토글과 1:1)은 대응이 맞지 않는다는 점도 알아 둘 것 — 루틴 리마인더는 그룹 토글이
 * 없어(상시, 마스터와 챌린지 음소거만 적용) 채널을 만들면 앱 설정에 짝이 없는 채널이 생긴다.
 */
public final class AndroidNotificationChannels {

    /**
     * 전 알림 공용 채널.
     *
     * <p><b>이 값은 바꾸지 않는다.</b> 채널 ID 를 바꾸면 기기에 남은 구 채널의 사용자 설정이
     * 버려지고 새 채널이 기본 활성으로 생성돼, 알림을 꺼 뒀던 사용자에게 다시 알림이 간다.
     */
    public static final String DEFAULT = "ruleup_default";

    /** 현재 쓰는 채널 전부. 늘어나면 여기부터 늘고, 늘리는 순간이 곧 위 전환 조건을 만족한 때다. */
    public static final List<String> ALL = List.of(DEFAULT);

    private AndroidNotificationChannels() {}
}

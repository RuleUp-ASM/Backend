-- 닉네임 1주일 잠금 폐지 (회원 정책 §3 개정).
--
-- 원래 의도는 사칭 방지였다 — 남이 버린 닉네임을 곧바로 가져가 그 사람 행세를 하는 것.
-- 그런데 점유 규칙만으로 이미 그 구간이 막혀 있었다:
--   · 변경을 신청해도 approved_nickname 은 이전 값을 그대로 들고 있어, 심사 중에는 아무도 못 가져간다
--   · 승인되는 순간에만 이전 값이 풀린다 (User#approveNickname)
-- 잠금은 그 위에 "승인 후 7일 더"를 얹은 층이었고, 그 대가로 멀쩡한 닉네임이 일주일간 아무도 못 쓰는
-- 상태로 떠 있었다.
--
-- "버린 본인은 되돌릴 수 있다"는 예외도 실제로는 닿지 않는 코드였다.
-- 닉네임 변경 주기가 30일이라 7일 안에 되돌리는 것 자체가 불가능하고,
-- 거절(REJECTED) 경로에서는 approved_nickname 이 아직 본인 것이라 잠금 없이도 되돌아간다.
--
-- 결론: 점유 규칙(승인 전 유지 → 승인 시 해제)만 남기고 잠금 테이블은 없앤다.


-- V11: 루틴 카탈로그 단일화 — V9 시드(id 1001~) 이전의 잔존 템플릿 제거
--
--  왜:
--   V9 는 구 템플릿과 충돌하지 않으려고 id 를 1001~ 로 띄워 "추가"만 했고, 지우지는 않았다.
--   V4 주석이 적어둔 대로 스테이징에는 리베이스라인 이전 템플릿(id ≤ 105)이 남아 있을 수 있다.
--   그런데 카탈로그를 읽는 두 경로가 모두 낮은 id 를 먼저 집는다:
--     · RecommendationService — 정렬이 (score desc, templateId asc) 라 세그먼트 점수가
--       아직 0인 초기에는 "가장 작은 id 3개"가 그대로 생성화면 추천 3건이 된다.
--     · ChallengeDraftService.fill — 카탈로그 순서(=PK 오름차순)대로 채운다.
--   즉 잔존 구 템플릿이 있으면 신규 시드는 화면에 뜨지도 못하고, 그 구 행이 과거 임포트
--   경로(latin1 클라이언트 등)에서 깨진 채로 들어왔다면 깨진 제목·설명이 그대로 노출된다.
--
--  안전성:
--   · RoutineTemplate 을 참조하는 FK 는 RoutineVerification 하나뿐이라 자식부터 지운다.
--   · challenges.template_id 는 V6 이후 소프트 참조(FK 없음)라 위반이 나지 않는다.
--     참조하던 방의 인증 설정은 challenges 행의 verificationConfig 에 이미 스냅샷돼 있어
--     판정에는 영향이 없다(상세 화면의 표시 문구만 템플릿 없음으로 폴백).
--   · 대상이 없으면 0건 삭제로 끝나는 멱등 마이그레이션이다.
--
--  이후 카탈로그의 진실은 V9(+후속 시드) 하나다. 시드를 갱신했으면 앱을 재시작해
--  RoutineCatalog 메모리 캐시를 비운다.
-- =====================================================================

DELETE FROM `RoutineVerification` WHERE `templateId` < 1000;
DELETE FROM `RoutineTemplate`     WHERE `id` < 1000;

-- 유저×귀속일 조회 인덱스 (인증 공통 5-6 GPS 파기 · 마이페이지 캘린더)
--
-- GPS 좌표 파기가 「그 유저의 그 날짜에 <b>아직 확정되지 않은 판정</b>이 남아 있는가」를 물어야 한다.
-- 한 사용자의 위치 원본은 여러 챌린지가 공유하므로, 한 챌린지가 먼저 확정됐다고 좌표를 지우면
-- 같은 날짜의 다른 챌린지가 D+2 에 확정될 때 판정할 근거가 없다.
--
-- 그 질문을 인덱스 없이 던지면 파기 배치가 VerificationDaily 를 통째로 훑는다. 기존
-- `findByUserIdAndTargetDate`(캘린더 당일 보강·리마인더 일괄 조회)도 같은 모양이라 함께 덕을 본다.
-- status 를 뒤에 붙여 커버링으로 만든다 — 파기 판단은 「PENDING 이 있나」만 보면 끝난다.
-- =====================================================================

CREATE INDEX `ixVerificationDailyUserDate` ON `VerificationDaily` (`userId`, `targetDate`, `status`);

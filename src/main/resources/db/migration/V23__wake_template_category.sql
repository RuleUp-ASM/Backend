-- ======================================================================
-- 기상 루틴 카테고리를 기상·수면으로 맞춘다
--
-- 루틴이 매칭되면 방 카테고리는 루틴의 카테고리를 따른다(ChallengeDraftService). 기상 루틴 둘이
-- 다른 카테고리로 시드돼 있어서 기상 방이 학습·커리어로 만들어졌다(prod 2026-11-01 「평일 아침 5시 30분 기상」
-- → STUDY, 「아침 6시 전 기상하기」 → CAREER_PRODUCTIVITY).
--   1505 평일 6시에 일어나기          CAREER_PRODUCTIVITY → WAKE_SLEEP
--   1507 시험 기간 5시 30분에 일어나기  STUDY               → WAKE_SLEEP
--
-- 이미 만들어진 방(challenges.category)은 바꾸지 않는다 — 카테고리는 생성 뒤 수정할 수 없는 값이고
-- 방장이 그 카테고리로 만든 방이다. 앞으로 만드는 방부터 기상·수면으로 나간다.
-- ======================================================================

UPDATE `RoutineTemplate`
   SET `category` = 'WAKE_SLEEP'
 WHERE `id` IN (1505, 1507);

-- =====================================================================
-- 정원 판정·방 단위 재집계를 위한 커버링 인덱스 (탐색 백엔드 12 · 원천 인덱스 확인)
--
-- 두 경로가 「그 방의 ACTIVE 멤버가 몇 명인가」를 묻는다.
--   ① 정원 있는 방의 가입 트랜잭션 — 챌린지 행을 잠근 채로 세므로 여기가 느리면 그만큼
--      같은 방 가입 전체가 줄을 선다. 락을 쥔 시간이 곧 처리량이다.
--   ② 통계 재계산·표시값 재집계 — 방 하나씩 반복해서 부른다.
--
-- 지금 있는 인덱스로는 둘 다 만족하지 않는다.
--   `uq_member (challenge_id, user_id)` : 방으로 좁히지만 status 가 없어 행을 다 읽고 거른다.
--   `(user_id, status)`                 : 선두 컬럼이 사용자라 방으로 좁히지 못한다.
--
-- (challenge_id, status) 면 방으로 좁힌 뒤 status 로 다시 좁히고, 세는 데 필요한 컬럼이
-- 인덱스 안에 다 있어 테이블을 읽지 않는다.
-- =====================================================================

CREATE INDEX `ix_member_challenge_status`
    ON `challenge_members` (`challenge_id`, `status`);

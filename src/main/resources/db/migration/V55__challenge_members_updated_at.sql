-- =====================================================================
-- 멤버십 행의 마지막 변경 시각 (탐색 백엔드 9 「마지막 성공 실행 이후 변경 방 원천 재집계」)
--
-- 5분 보정은 <b>그 사이에 움직인 방만</b> 다시 계산해야 한다. 지금은 매 회차 후보 전체를
-- 재계산하는데, 방이 늘수록 같은 일을 반복하고 그만큼 인기 하락 반영도 늦어진다.
--
-- 「움직였다」의 신호가 방마다 셋인데, 그중 멤버십 쪽만 시각이 없었다.
--   challenges.updated_at        : 설정·상태 변경
--   challenge_join_events.joined_at : 가입·재입장
--   challenge_members            : ← 여기. 탈퇴·강퇴와 <b>판정 확정</b>(진행률 비정규화)이 여기 찍힌다
--
-- 판정 확정이 특히 중요하다. 완주율·유지율은 그 이벤트로 갱신되는데, 이벤트가 유실되면
-- 다음 03:30 까지 틀린 값이 그대로 나간다 — 5분 보정이 그걸 잡으라고 있는 배치다.
-- =====================================================================

ALTER TABLE `challenge_members`
    ADD COLUMN `updated_at` DATETIME(6) NOT NULL
        DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
        COMMENT '행이 마지막으로 바뀐 시각. 5분 보정이 「그 사이 움직인 방」을 찾는 입력';

-- 보정이 「이 시각 이후 바뀐 멤버가 있는 방」을 묻는다. 시각으로 먼저 좁힌 뒤 방으로 모은다.
CREATE INDEX `ix_member_updated_at` ON `challenge_members` (`updated_at`);
